import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
const html=fs.readFileSync('../migration-backup-release/respaldo.html','utf8');
const context=vm.createContext({crypto:webcrypto,TextEncoder,document:{getElementById:()=>({})}});
vm.runInContext(html.match(/<script>([\s\S]*?)<\/script>/)[1],context);
const data={reports:[{id:'existing',photos:[{data:'original-photo'}]}],actions:[],plans:[],users:[{id:'user',passwordHash:'excluded'}],notices:[],reads:{}};
const raw=JSON.stringify(data);
const storage={length:2,key:i=>['sm-workspace-v1','firebase:authUser'][i],getItem:key=>key==='sm-workspace-v1'?raw:'excluded-token'};
const backup=await context.createBackup(storage);
assert.equal(backup.data.reports[0].photos[0].data,'original-photo');
assert.equal(backup.data.users[0].passwordHash,undefined);
assert.equal(storage.getItem('sm-workspace-v1'),raw);
assert(!JSON.stringify(backup).includes('excluded'));
const {verifyBackup}=await import('./verify-migration-backup.mjs');
assert.equal(verifyBackup(backup).counts.reports,1);
await assert.rejects(()=>context.createBackup({length:0}),/no contiene/);
console.log('Respaldo: integridad, evidencias, exclusión de credenciales y conservación del original: OK');
